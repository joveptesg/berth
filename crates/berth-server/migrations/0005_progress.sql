-- Append-only progress journal; idempotent by (device_id, event_id).
CREATE TABLE progress_events (
    id          TEXT PRIMARY KEY,
    tenant_id   TEXT NOT NULL REFERENCES tenants (id),
    user_id     TEXT NOT NULL REFERENCES users (id),
    device_id   TEXT NOT NULL REFERENCES devices (id),
    event_id    TEXT NOT NULL, -- UUIDv7 generated by the client
    book_id     TEXT NOT NULL REFERENCES books (id),
    position_ms BIGINT NOT NULL,
    speed       DOUBLE PRECISION NOT NULL DEFAULT 1,
    event_type  TEXT NOT NULL,
    client_ts   BIGINT NOT NULL,
    server_ts   BIGINT NOT NULL,
    UNIQUE (device_id, event_id)
);
CREATE INDEX progress_events_book_idx ON progress_events (tenant_id, user_id, book_id);

-- Current position per user and book: last write wins by client_ts corrected for device clock skew.
CREATE TABLE progress_current (
    tenant_id   TEXT NOT NULL REFERENCES tenants (id),
    user_id     TEXT NOT NULL REFERENCES users (id),
    book_id     TEXT NOT NULL REFERENCES books (id),
    position_ms BIGINT NOT NULL,
    finished    BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at  BIGINT NOT NULL, -- corrected client_ts of the winning event
    PRIMARY KEY (tenant_id, user_id, book_id)
);
